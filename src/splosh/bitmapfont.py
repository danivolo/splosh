GLYPHS = {}
for _c, (_off, _rows) in _RAW.items():
    GLYPHS[_c] = (_off, np.array([[ch == "#" for ch in r] for r in _rows.split("/")], dtype=bool))


def text_size(text, scale=1):
    """(height, width) in pixels of `text_mask(text, scale)`."""
    return CELL_H * scale, max(0, len(text) * CELL_W - 1) * scale


def text_mask(text, scale=1):
    """Boolean ink mask (CELL_H*scale, width) of a single line of text. Characters without a glyph are drawn as '?'."""
    h, w = text_size(text, scale)
    m = np.zeros((CELL_H, max(1, len(text) * CELL_W)), dtype=bool)
    for k, c in enumerate(text):
        off, g = GLYPHS.get(c, GLYPHS["?"])
        m[off:off + g.shape[0], k * CELL_W:k * CELL_W + 5] = g
    m = m[:, :max(1, w // scale)] if scale else m
    return np.kron(m, np.ones((scale, scale), dtype=bool)) if scale > 1 else m
